from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class AssistantChatRequest(BaseModel):
    """Payload sent by the user to ask a question to the AI Project Assistant."""
    message: str = Field(..., min_length=1, max_length=5000, description="Natural-language question or query")
    conversation_id: Optional[str] = Field(None, description="Existing conversation session ID for continuity")
    project_id: Optional[int] = Field(None, description="Target project ID (if not provided in URL path)")


class AssistantSourceItem(BaseModel):
    """Referenced supporting entity, file, risk, or metric."""
    type: str = Field(..., description="file, component, risk, health, dependency, hotspot, or metric")
    name: str = Field(..., description="Display name of the entity or file")
    path: Optional[str] = Field(None, description="Relative file path within repository if applicable")
    detail: Optional[str] = Field(None, description="Concise context or explanation of relevance")


class AssistantChatResponse(BaseModel):
    """Primary response returned to the frontend."""
    answer: str = Field(..., description="Clean, professional, natural-language Markdown answer generated by Qwen")
    conversation_id: str = Field(..., description="Session identifier for multi-turn conversation memory")
    sources: List[AssistantSourceItem] = Field(default_factory=list, description="Grounding source references")
    related_components: List[str] = Field(default_factory=list, description="Relevant software components or modules")
    related_risks: List[str] = Field(default_factory=list, description="Relevant risk titles or types")
    recommendations: List[str] = Field(default_factory=list, description="Actionable recommendations")
    suggested_questions: List[str] = Field(default_factory=list, description="Contextual follow-up questions")


class OllamaStatusResponse(BaseModel):
    """Health and model availability status of the AI Assistant provider."""
    connected: bool = Field(..., description="Whether provider responded successfully")
    base_url: str = Field(..., description="Target API base URL")
    model: str = Field(..., description="Configured model name")
    model_available: bool = Field(..., description="Whether configured model is ready")
    available_models: List[str] = Field(default_factory=list, description="List of models available")
    error: Optional[str] = Field(None, description="Error message if provider is unreachable")
    provider: Optional[str] = Field(default="groq", description="Active AI provider: groq or ollama")


class ConversationMessageSchema(BaseModel):
    """Single turn in a multi-turn conversation."""
    id: str = Field(..., description="Unique message UUID")
    role: str = Field(..., description="'user' or 'assistant'")
    content: str = Field(..., description="Message text or Markdown")
    timestamp: str = Field(..., description="ISO 8601 UTC timestamp")
    sources: Optional[List[AssistantSourceItem]] = Field(default=None, description="Grounding sources for assistant")
    suggested_questions: Optional[List[str]] = Field(default=None, description="Follow-up suggestions")


class ConversationHistoryResponse(BaseModel):
    """Chronological conversation history for a session."""
    conversation_id: str = Field(...)
    project_id: int = Field(...)
    messages: List[ConversationMessageSchema] = Field(default_factory=list)


class SuggestedQuestionsResponse(BaseModel):
    """Initial or contextual suggested prompts for a project."""
    project_id: int = Field(...)
    project_name: str = Field(...)
    questions: List[str] = Field(default_factory=list)
